// Node 24 strips types from the pinned MIT geometry; no npm/runtime dependency.
import { readFile, writeFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('docs/design/ui-component-license-manifest.json', root), 'utf8'));
for (const component of manifest.components) {
  for (const file of component.files) {
    const digest = createHash('sha256').update(await readFile(new URL(file.path, root))).digest('hex');
    if (digest !== file.sha256) throw new Error(`Unreviewed upstream asset change: ${file.path}`);
  }
}
const files = ['src/engine/core.ts', 'src/engine/profiles.ts', 'src/engine/lattice.ts', 'src/engine/ribbon.ts', 'src/engine/web.ts', 'src/presets.ts'];
let output = '/* Generated by scripts/build-agent-motion.mjs.\n' + await readFile(new URL('third_party/thinking-orbs/LICENSE', root), 'utf8') + '*/\n(() => {\n"use strict";\n';
for (const file of files) {
  const source = await readFile(new URL('third_party/thinking-orbs/' + file, root), 'utf8');
  const standalone = source.replace(/^import[^;]*;\s*/gm, '').replace(/^export /gm, '');
  output += '\n// thinking-orbs/' + file + '\n' + stripTypeScriptTypes(standalone).replace(/[\t ]+$/gm, '') + '\n';
}
output += await readFile(new URL('hartevo-rs/desktop/motion/controller.js', root), 'utf8');
output += '\n})();\n';
const target = new URL('hartevo-rs/desktop/assets/agent-motion.js', root);
if (process.argv.includes('--check')) {
  if (output !== await readFile(target, 'utf8')) throw new Error('agent-motion.js is stale; run node scripts/build-agent-motion.mjs');
} else await writeFile(target, output);
